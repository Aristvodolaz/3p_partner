/**
 * Жизненный цикл заявки: Запланировано → Приёмка → Хранение → В работе →
 * Готово → Отгружено → Закрыто. «Дефект» — отдельный статус для претензии/брака,
 * не входящий в основную линейку.
 */
export const REQUEST_STATUSES = [
  'Запланировано',
  'Приёмка',
  'Хранение',
  'В работе',
  'Готово',
  'Отгружено',
  'Закрыто',
  'Дефект',
] as const;

export type RequestStatus = (typeof REQUEST_STATUSES)[number];

/** Основная линейка этапов (без «Дефекта» — он вне линейки, только вручную) */
const STATUS_ORDER = [
  'Запланировано',
  'Приёмка',
  'Хранение',
  'В работе',
  'Готово',
  'Отгружено',
  'Закрыто',
];

/**
 * Продвигает статус заявки вперёд по линейке, если целевой статус дальше текущего.
 * Никогда не двигает назад и не трогает статусы вне линейки (например, «Дефект»,
 * куда/откуда переход возможен только вручную).
 */
export function advanceStatus(current: string, target: string): string {
  const ci = STATUS_ORDER.indexOf(current);
  const ti = STATUS_ORDER.indexOf(target);
  if (ci === -1 || ti === -1) return current;
  return ti > ci ? target : current;
}
